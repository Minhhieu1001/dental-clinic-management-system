export function calcStatsFromDentists(dentists) {
  return {
    total: dentists.length,
    active: dentists.filter((d) => d.displayStatus === 'active').length,
    onLeave: dentists.filter((d) => d.displayStatus === 'leave').length,
    blocked: dentists.filter((d) => d.displayStatus === 'locked').length,
  };
}

export function getMockDentistData() {
  const dentists = MOCK_RAW_DENTISTS.map((dentist, index) => mapDentistFromApi(dentist, index));
  return {
    dentists,
    stats: calcStatsFromDentists(dentists),
  };
}

/** Giả lập delay API để test loading state */
export function fetchMockDentistData(delayMs = 400) {
  return new Promise((resolve) => {
    setTimeout(() => resolve(getMockDentistData()), delayMs);
  });
}
